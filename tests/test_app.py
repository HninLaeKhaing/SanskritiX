from pathlib import Path

import pytest
from streamlit.testing.v1 import AppTest

APP_PATH = Path(__file__).parents[1] / "sankritix" / "app.py"


def test_app_shows_honest_preview_when_model_is_missing(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    monkeypatch.chdir(tmp_path)
    app = AppTest.from_file(str(APP_PATH), default_timeout=60).run()

    assert not app.exception
    assert any("Preview mode" in item.value for item in app.info)
    assert any(
        item.value == "SAMPLE RESULT CARD · NOT GENERATED BY A MODEL"
        for item in app.caption
    )
    assert app.file_uploader[0].disabled
    assert len(app.selectbox) == 2
    assert "Gond painting" in app.selectbox[0].options
    assert "Warli painting" in app.selectbox[1].options


def test_learning_explorer_switches_to_selected_tradition(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    monkeypatch.chdir(tmp_path)
    app = AppTest.from_file(str(APP_PATH), default_timeout=60).run()

    app.selectbox[0].select("warli").run()

    assert not app.exception
    assert any(item.value == "Warli painting" for item in app.subheader)
    assert any("Maharashtra" in item.value for item in app.markdown)


def test_quiz_reveals_feedback_then_advances_to_next_question(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    monkeypatch.chdir(tmp_path)
    app = AppTest.from_file(str(APP_PATH), default_timeout=60).run()
    app.radio[0].set_value("Rhythmic repeated lines and marks").run()
    app.button(key="check_gond_0").click().run()

    assert not app.exception
    assert any("That's right." in item.value for item in app.success)
    assert app.button(key="next_gond_0").label == "Next question"

    app.button(key="next_gond_0").click().run()

    assert not app.exception
    assert any(
        "Which subjects may appear in contemporary Gond paintings?" in item.label
        for item in app.radio
    )
